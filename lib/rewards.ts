/** Nombre del premio que entrega un reto de ese nivel, para anunciarlo antes. */
export function rewardLabelFor(profileId: ProfileId, tier: ChallengeTier): string | null {
  const deck = DECKS[profileId];
  if (!deck) return null;

  const nameOf = (cards?: Record<ChallengeTier, Reward[]>) => {
    const sample = cards?.[tier][0];
    if (!sample) return null;
    return deck.labels[sample.rarity] ?? SHARED_LABELS[sample.rarity] ?? null;
  };

  const main = nameOf(deck.cards);
  if (!main) return null;

  // Con mazos de más se anuncian todos: es parte de lo que se está jugando.
  const rest = [nameOf(deck.bonus), nameOf(deck.extra)].filter(
    (label): label is string => !!label,
  );

  return rest.length > 0 ? `${main} + ${rest.map((l) => l.toLowerCase()).join(' + ')}` : main;
}

